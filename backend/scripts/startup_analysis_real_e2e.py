def create_real_startup(session: Session) -> Startup:
    startup = Startup(
        name=E2E_STARTUP_NAME,
        legal_name=None,
        description=E2E_STARTUP_DESCRIPTION,
        sector=E2E_STARTUP_SECTOR,
        industry=E2E_STARTUP_INDUSTRY,
        stage=StartupStage.IDEA,
        status=StartupStatus.ACTIVE,
        founded_year=E2E_STARTUP_FOUNDED_YEAR,
        website=None,
        headquarters=E2E_STARTUP_HEADQUARTERS,
    )

    session.add(startup)
    session.flush()

    session.add(
        Founder(
            startup=startup,
            full_name=E2E_FOUNDER_NAME,
            designation=FounderRole.CEO,
            experience_years=E2E_FOUNDER_EXPERIENCE_YEARS,
            previous_companies=E2E_FOUNDER_PREVIOUS_COMPANIES,
            education=None,
            notes=None,
            email=None,
        )
    )

    session.commit()
    session.refresh(startup)
    return startup


def create_real_document(
    session: Session,
    startup: Startup,
    storage: StorageService,
) -> Document:
    upload_service = create_upload_service(session, storage)

    document = upload_service.upload(
        UploadRequest(
            startup_id=startup.id,
            document_type=DocumentType.OTHER,
            title=E2E_DOCUMENT_TITLE,
            filename=E2E_DOCUMENT_FILENAME,
            mime_type=E2E_DOCUMENT_MIME_TYPE,
            description=E2E_DOCUMENT_DESCRIPTION,
            data=E2E_DOCUMENT_CONTENT.encode("utf-8"),
        )
    )

    session.refresh(document)
    return document


def validate_real_document(
    storage: StorageService,
    document: Document,
    startup: Startup,
) -> None:
    assert document.id is not None
    assert document.startup_id == startup.id
    assert document.document_type == DocumentType.OTHER
    assert document.title == E2E_DOCUMENT_TITLE
    assert document.filename == E2E_DOCUMENT_FILENAME
    assert document.original_filename == E2E_DOCUMENT_FILENAME
    assert document.mime_type == E2E_DOCUMENT_MIME_TYPE
    assert document.status == DocumentStatus.UPLOADED
    assert document.file_size == len(E2E_DOCUMENT_CONTENT.encode("utf-8"))
    assert document.file_hash
    assert document.storage_path

    assert storage.exists(document.storage_path)
    assert storage.open(document.storage_path) == E2E_DOCUMENT_CONTENT.encode("utf-8")


