def main() -> int:
    print_header()

    model_path = Path(settings.qwen_model_path)
    if not model_path.exists():
        print()
        print("ERROR: Qwen model file does not exist.")
        print(f"       {model_path}")
        return 1

    storage = create_storage_service()
    engine = create_test_engine()
    startup: Startup | None = None
    document: Document | None = None
    captured_profiles: list[InvestmentProfile] = []

    def capture_profile(profile: InvestmentProfile) -> None:
        captured_profiles.append(profile)

    try:
        print()
        print("-" * 80)
        print("Creating E2E database")
        print("-" * 80)
        Base.metadata.create_all(engine)

        session = create_session(engine)
        try:
            print()
            print("-" * 80)
            print("Creating startup fixture")
            print("-" * 80)
            startup = create_real_startup(session)
            print(f"Startup ID       : {startup.id}")

            print()
            print("-" * 80)
            print("Creating real document fixture")
            print("-" * 80)
            document = create_real_document(session, startup, storage)
            print(f"Document ID      : {document.id}")

            validate_real_document(storage, document, startup)
            print_document_summary(document)
            print()
            print("Document persistence/storage: PASS")

            session.refresh(startup)
            documents = list(startup.documents or [])
            assert any(item.id == document.id for item in documents)
            print("Startup -> Document relationship: PASS")

            # ----------------------------------------------------------
            # C.6.1 diagnostic observer
            # ----------------------------------------------------------
            # Build the same production document-intelligence dependency
            # graph used by the application factory, but inject the
            # diagnostic observer. The application service still owns
            # startup resolution and persistence; only the orchestrator
            # dependency is supplied explicitly so C.6.1 can inspect the
            # raw InvestmentProfile without a second document-analysis pass.
            documents_service = DocumentService(session)
            processing = DocumentProcessingService(
                documents=documents_service,
                storage=storage,
                processors=create_processor_factory(),
                chunker=TextChunker(),
            )
            intelligence = InvestmentIntelligenceService(
                factory=create_intelligence_factory(),
            )
            document_intelligence = (
                StartupAnalysisDocumentIntelligenceService(
                    document_processing=processing,
                    intelligence=intelligence,
                    profile_observer=capture_profile,
                )
            )
            orchestrator = StartupAnalysisOrchestrator(
                document_intelligence_service=document_intelligence,
            )

            print()
            print("-" * 80)
            print("Running production startup analysis")
            print("-" * 80)
            print()
            print("IMPORTANT: This invokes the real Qwen GGUF model.")
            print("C.6.1 captures the raw InvestmentProfile before mapping.")
            print()

            analysis_start = time.perf_counter()

            application_service = StartupAnalysisApplicationService(
                session=session,
                orchestrator=orchestrator,
            )

            analysis = application_service.analyze(
                startup_id=startup.id,
                mode=E2E_MODE,
            )

            elapsed = time.perf_counter() - analysis_start
            print(f"Analysis time    : {elapsed:.2f} sec")

            # ----------------------------------------------------------
            # C.6.1 raw profile diagnostics
            # ----------------------------------------------------------
            assert captured_profiles
            for profile in captured_profiles:
                print_investment_profile(profile)

            print()
            print("-" * 80)
            print("Validating persisted analysis")
            print("-" * 80)
            validate_persisted_analysis(analysis, startup)
            print("Persistence validation: PASS")

            print()
            print("-" * 80)
            print("Validating document intelligence enrichment")
            print("-" * 80)
            validate_document_enrichment(analysis, captured_profiles)
            print_mapped_input(analysis.input_snapshot)

            print_analysis_summary(analysis)

            print()
            print("-" * 80)
            print("Validating analysis history")
            print("-" * 80)
            repository = StartupAnalysisRepository(session)
            history_service = StartupAnalysisHistoryService(
                repository=repository,
            )
            validate_history_round_trip(
                history_service,
                startup,
                analysis,
            )
            print("History round-trip: PASS")

            print()
            print("=" * 80)
            print("REAL STARTUP ANALYSIS E2E: PASS")
            print("=" * 80)
            print()
            print("Validated:")
            print("  [PASS] Real Startup ORM")
            print("  [PASS] Real Founder ORM")
            print("  [PASS] Real UploadService")
            print("  [PASS] Real StorageService")
            print("  [PASS] Real Document ORM")
            print("  [PASS] Document storage round-trip")
            print("  [PASS] Startup -> Document relationship")
            print("  [PASS] StartupAnalysisApplicationService")
            print("  [PASS] StartupAnalysisOrchestrator")
            print("  [PASS] AnalysisInputBuilder")
            print("  [PASS] DocumentProcessingService")
            print("  [PASS] InvestmentIntelligenceService")
            print("  [PASS] Raw InvestmentProfile captured")
            print("  [PASS] Document intelligence enrichment")
            print("  [PASS] FinancialMetricsService")
            print("  [PASS] Real QwenProvider")
            print("  [PASS] StartupAnalysisParser")
            print("  [PASS] StartupAnalysisExecution")
            print("  [PASS] StartupAnalysisPersistenceService")
            print("  [PASS] StartupAnalysisMapper")
            print("  [PASS] StartupAnalysisRepository")
            print("  [PASS] Persisted execution artifacts")
            print("  [PASS] StartupAnalysisHistoryService")
            print()
            return 0

        finally:
            session.close()

    except Exception as exc:
        print()
        print("=" * 80)
        print("REAL STARTUP ANALYSIS E2E: FAILED")
        print("=" * 80)
        print()
        print(f"Exception type   : {type(exc).__name__}")
        print(f"Exception        : {exc}")
        print()
        traceback.print_exc()
        return 1

    finally:
        cleanup_document_storage(storage, document)
        Base.metadata.drop_all(engine)
        engine.dispose()


if __name__ == "__main__":
    raise SystemExit(main())
