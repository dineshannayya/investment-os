def cleanup_document_storage(
    storage: StorageService | None,
    document: Document | None,
) -> None:
    if storage is None or document is None or not document.storage_path:
        return

    try:
        if storage.exists(document.storage_path):
            storage.delete(document.storage_path)
    except Exception as exc:
        print("WARNING: Failed to remove E2E document from storage:")
        print(f"         {document.storage_path}")
        print(f"         {exc}")


