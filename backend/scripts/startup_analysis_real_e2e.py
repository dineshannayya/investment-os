def print_mapped_input(input_snapshot: dict) -> None:
    """Print the persisted StartupAnalysisInput snapshot by analysis section."""
    print()
    print("=" * 80)
    print("STARTUP ANALYSIS INPUT AFTER DOCUMENT ENRICHMENT")
    print("=" * 80)

    for field in (
        "product",
        "market",
        "traction",
        "financials",
        "business_model",
    ):
        print()
        print(f"{field.upper()}")
        print("-" * 80)
        value = input_snapshot.get(field)
        if value is None:
            print("<empty>")
        elif isinstance(value, dict):
            for key, item in value.items():
                print(f"{key:<28}: {item}")
        else:
            print(value)


def validate_document_enrichment(analysis, profiles: list[InvestmentProfile]) -> None:
    assert profiles, "No InvestmentProfile was captured by C.6.1 observer."

    input_snapshot = analysis.input_snapshot
    assert input_snapshot is not None
    assert isinstance(input_snapshot, dict)

    fields = (
        "product",
        "market",
        "traction",
        "financials",
        "business_model",
    )

    populated = [
        field for field in fields
        if input_snapshot.get(field) is not None
    ]

    assert populated, (
        "Document was processed and an InvestmentProfile was produced, "
        "but no supported StartupAnalysisInput fields were populated."
    )

    print()
    print(
        "Document enrichment: PASS "
        f"({', '.join(populated)})"
    )


